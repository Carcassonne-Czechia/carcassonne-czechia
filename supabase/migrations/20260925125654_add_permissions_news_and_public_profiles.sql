create or replace function private.protect_profile_fields()
returns trigger
language plpgsql
set search_path = private, pg_catalog
as $$
begin
	if not (select private.has_permission('admin'))
	and (
		new.user_id is distinct from old.user_id
		or new.player_id is distinct from old.player_id
		or new.created_at is distinct from old.created_at
	) then
		raise exception 'Only admins can change protected profile fields';
	end if;

	new.updated_at := now();
	return new;
end;
$$;

revoke execute on function private.protect_profile_fields() from public;
grant execute on function private.protect_profile_fields() to authenticated;

create trigger profiles_protect_fields
	before update on public.profiles
	for each row execute procedure private.protect_profile_fields();

create or replace function private.protect_news_fields()
returns trigger
language plpgsql
set search_path = private, pg_catalog
as $$
begin
	if not (select private.has_permission('admin'))
	and (
		new.author_id is distinct from old.author_id
		or new.created_at is distinct from old.created_at
	) then
		raise exception 'Only admins can change protected news fields';
	end if;

	return new;
end;
$$;

revoke execute on function private.protect_news_fields() from public;
grant execute on function private.protect_news_fields() to authenticated;

create trigger news_protect_fields
	before update on public.news
	for each row execute procedure private.protect_news_fields();

