create schema if not exists private;

revoke all on schema private from public;
grant usage on schema private to anon, authenticated;

create table public.permission_catalog (
	code text primary key,
	description text not null
);

insert into public.permission_catalog (code, description)
values
	('admin', 'Manage all application data and permissions'),
	('news.edit', 'Create, edit, and delete owned news')
on conflict (code) do nothing;

create table public.user_permissions (
	user_id uuid not null references auth.users (id) on delete cascade,
	permission_code text not null references public.permission_catalog (code) on delete restrict,
	granted_at timestamptz not null default now(),
	granted_by uuid not null references auth.users (id) on delete restrict,
	primary key (user_id, permission_code)
);

create or replace function private.has_permission(required_permission text)
returns boolean
language sql
stable
security definer
set search_path = private, pg_catalog
as $$
	select exists (
		select 1
		from public.user_permissions
		where user_id = (select auth.uid())
		and permission_code = required_permission
	);
$$;

revoke execute on function private.has_permission(text) from public;
grant execute on function private.has_permission(text) to authenticated;

create table public.news (
	id bigint generated by default as identity primary key,
	author_id uuid not null default auth.uid() references auth.users (id) on delete restrict,
	created_at timestamptz not null default now(),
	hide_at timestamptz,
	title_cs text,
	title_en text,
	content_cs text,
	content_en text,
	image text,
	constraint news_czech_consistency_check check ((title_cs is null) = (content_cs is null)),
	constraint news_english_consistency_check check ((title_en is null) = (content_en is null))
);

create index news_publication_idx on public.news (created_at desc)
	where hide_at is null;

